"""Point-cloud OBJ for an image volume — a vectorised port of NRRDtools/maxProjVol.py.

Same output as the original, pass for pass: the same thresholds (max/p, p = 1, 2, …), the same loop
condition, the same candidate voxels (per column the first argmax and the last maximum beyond it), the
same strict ``> th`` test, the same vertex order, the same surface passes for binary (<= 3 grey-level)
volumes and the same "v x y z r" lines. Only the ±1 voxel jitter is drawn from numpy instead of
``random.uniform`` (``jitter=False`` disables it, which is how the parity test compares outputs).

The original loops over voxels in Python and builds the file by string concatenation; this processes a
whole pass with array operations (seconds rather than minutes for a 1210x566x174 brain).
"""
import numpy as np

HEADER = '####\n#\n# OBJ File Generated by VirtualFlyBrain.org\n#\n####\n'


def _column_picks(cols, th):
    """cols: (N, L) columns. Returns (idx1, ok1, idx2, ok2): first argmax, and the last maximum among
    positions > idx1 + 1 (only where idx1 < L - 2), each with its `value > th` test."""
    n, length = cols.shape
    rows = np.arange(n)
    l0 = cols.argmax(axis=1)
    ok0 = cols[rows, l0] > th
    has2 = l0 < length - 2
    masked = cols.astype(np.int64, copy=True)
    pos = np.arange(length)
    masked[pos[None, :] <= (l0 + 1)[:, None]] = -1          # only positions after l0 + 1
    rev_idx = masked[:, ::-1].argmax(axis=1)                 # first max of the reversed tail = last max
    l1 = length - 1 - rev_idx
    ok1 = has2 & (cols[rows, l1] > th)
    return l0, ok0, l1, ok1


def _emit(a, b, c, order_keys, vals, out):
    """Collect points (a, b, c are full-volume x, y, z index arrays) in the original visiting order."""
    if len(a):
        order = np.lexsort(order_keys[::-1])
        out.append((a[order], b[order], c[order], vals[order]))


def point_cloud(data, spacing, jitter=True, rng=None):
    """Return the OBJ text for volume ``data`` (x, y, z order as read by pynrrd) and voxel ``spacing``
    (the diagonal of 'space directions', signs kept, exactly as maxProjVol uses it)."""
    data = np.array(data, copy=True)
    shape = data.shape
    vmax = data.max()
    sx, sy, sz = (float(s) for s in spacing)
    rng = rng or np.random.default_rng()
    bin_count = np.count_nonzero(np.bincount(data.ravel().astype(np.int64)))
    binary = bin_count < 4
    pieces = []          # list of (x, y, z, value) arrays, in output order
    c = 0
    p = 1.0
    th = 255

    while ((c < 15000 and th > 10) or (p < 10 and c < 250000)) and (bin_count > 3 or c < 10):
        th = vmax / p
        colmax = data.max(axis=2)
        xs, ys = np.nonzero(colmax >= th)                   # x-major, then y: the original's loop order
        if len(xs):
            cols = data[xs, ys, :]
            l0, ok0, l1, ok1 = _column_picks(cols, th)
            # per column the original visits l0 then l1: interleave, keep the passing ones
            zz = np.stack([l0, l1], 1).ravel()
            ok = np.stack([ok0, ok1], 1).ravel()
            px, py, pz = np.repeat(xs, 2)[ok], np.repeat(ys, 2)[ok], zz[ok]
            vals = data[px, py, pz]
            pieces.append((px, py, pz, vals))
            c += len(px)
            if binary and len(px):
                data[px, py, pz] = 0
        p += 1.0

    if binary:
        # surface pass A: columns along x, visited z-major then y
        colmax = data.max(axis=0)                            # (y, z)
        zs_order = np.nonzero(colmax.T >= th)                # (z, y) pairs, z-major
        zsel, ysel = zs_order
        if len(zsel):
            cols = data[:, ysel, zsel].T                     # (N, X)
            l0, ok0, l1, ok1 = _column_picks(cols, th)
            xx = np.stack([l0, l1], 1).ravel(); ok = np.stack([ok0, ok1], 1).ravel()
            px, py, pz = xx[ok], np.repeat(ysel, 2)[ok], np.repeat(zsel, 2)[ok]
            vals = data[px, py, pz]
            pieces.append((px, py, pz, vals)); c += len(px)
            data[px, py, pz] = 0
        # surface pass B: columns along y, visited z-major then x
        colmax = data.max(axis=1)                            # (x, z)
        zsel, xsel = np.nonzero(colmax.T >= th)
        if len(zsel):
            cols = data[xsel, :, zsel]                       # (N, Y)
            l0, ok0, l1, ok1 = _column_picks(cols, th)
            yy = np.stack([l0, l1], 1).ravel(); ok = np.stack([ok0, ok1], 1).ravel()
            px, py, pz = np.repeat(xsel, 2)[ok], yy[ok], np.repeat(zsel, 2)[ok]
            vals = data[px, py, pz]
            pieces.append((px, py, pz, vals)); c += len(px)
            data[px, py, pz] = 0

    if not pieces:
        return HEADER
    px = np.concatenate([q[0] for q in pieces]).astype(np.float64)
    py = np.concatenate([q[1] for q in pieces]).astype(np.float64)
    pz = np.concatenate([q[2] for q in pieces]).astype(np.float64)
    vals = np.concatenate([q[3] for q in pieces]).astype(np.float64)
    n = len(px)
    if jitter:
        ux, uy, uz = rng.uniform(-1, 1, n), rng.uniform(-1, 1, n), rng.uniform(-1, 1, n)
    else:
        ux = uy = uz = np.zeros(n)
    X = (px * sx + ux * sx).tolist()
    Y = (py * sy + uy * sy).tolist()
    Z = (pz * sz + uz * sz).tolist()
    R = (vals / 256.0).tolist()
    return HEADER + ''.join(f'v {x!r} {y!r} {z!r} {r!r}\n' for x, y, z, r in zip(X, Y, Z, R))
